#!/usr/bin/env python3
"""Write docs/CODE_INDEX.md: one compact entry per .gd file (class, signals, public funcs, preloads).

Read the index before exploring the code; rerun this script after changing .gd files.
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "CODE_INDEX.md"

CLASS = re.compile(r"^(class_name|extends)\s+(\S+)", re.MULTILINE)
SIGNAL = re.compile(r"^signal\s+(\w+)", re.MULTILINE)
# Top-level public functions only; private (_x) and inner-class methods are left out to keep the index small.
FUNC = re.compile(r"^(static\s+)?func\s+([a-zA-Z]\w*)\s*\(([^)]*)\)", re.MULTILINE)
PRELOAD = re.compile(r"""(?:preload|load)\(\s*["']res://([^"']+\.gd)["']""")


def entry(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    head = " ".join(f"{kind} {name}" for kind, name in CLASS.findall(text))
    lines = [f"### {path.relative_to(ROOT).as_posix()} ({text.count(chr(10))} lines)" + (f" — {head}" if head else "")]
    if signals := SIGNAL.findall(text):
        lines.append("- signals: " + ", ".join(signals))
    funcs = [("static " if s else "") + name + "(" + " ".join(args.split()) + ")" for s, name, args in FUNC.findall(text)]
    if funcs:
        lines.append("- funcs: " + "; ".join(funcs))
    if deps := sorted(set(PRELOAD.findall(text))):
        lines.append("- uses: " + ", ".join(deps))
    return "\n".join(lines)


def build() -> str:
    files = sorted(p for p in ROOT.rglob("*.gd") if not {".git", ".godot"} & set(p.parts))
    body = "\n\n".join(entry(p) for p in files)
    return (
        "# Code index (generated)\n\n"
        "Generated by `python tools/build_code_index.py`; do not edit by hand. "
        "Public API only: private `_funcs` and inner classes are omitted.\n\n"
        f"{len(files)} files.\n\n{body}\n"
    )


def selftest() -> None:
    sample = 'extends Node\nclass_name Foo\nsignal hit(x: int)\nconst B = preload("res://game/b.gd")\nfunc go(a: int,\n\tb: int) -> void:\n\tpass\nfunc _hidden():\n\tpass\n'
    assert CLASS.findall(sample) == [("extends", "Node"), ("class_name", "Foo")]
    assert SIGNAL.findall(sample) == ["hit"]
    assert [m[1] for m in FUNC.findall(sample)] == ["go"]
    assert PRELOAD.findall(sample) == ["game/b.gd"]


if __name__ == "__main__":
    selftest()
    OUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
